#!/usr/bin/env python3
"""Build the episode from tools/episode.py and tools/scenes/<id>.js.

Writes index.html, compositions/<id>.html, compositions/captions.html and
assets/lib/dialogue.js. Re-run after editing the episode data or a scene script."""
import html
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import episode as E  # noqa: E402

starts, t = {}, 0.0
for sid, dur, _ in E.SCENES:
    starts[sid] = t
    t += dur
TOTAL = t
DUR = {sid: dur for sid, dur, _ in E.SCENES}

# ---- dialogue timing ----
lines = []
for i, (sid, lt, who, text, note) in enumerate(E.LINES):
    words = len(text.split())
    want = max(1.9, 0.7 + 0.32 * words)
    nxt = None
    for sid2, lt2, *_ in E.LINES[i + 1 :]:
        if sid2 == sid:
            nxt = lt2
            break
    limit = (nxt if nxt is not None else DUR[sid]) - lt - 0.12
    dur = round(min(want, limit), 2)
    if dur < 0.6 + 0.25 * words:
        print(f"warning: line {i} ({text[:30]}…) only has {dur}s", file=sys.stderr)
    at = round(starts[sid] + lt, 3)
    lines.append(
        {
            "id": i,
            "at": at,
            "dur": dur,
            "talk": round(min(dur - 0.15, 0.35 + 0.27 * words), 2),
            "who": who,
            "text": text,
            "note": note,
            "voice": note != "öz-özünə",
        }
    )

with open(os.path.join(ROOT, "assets/lib/dialogue.js"), "w") as f:
    f.write("/* Generated by tools/build.py from tools/episode.py — do not edit by hand. */\n")
    f.write("window.T = window.T || {};\n")
    f.write("window.T.DIALOGUE = " + json.dumps(lines, ensure_ascii=False, indent=1) + ";\n")
    f.write("window.T.STARTS = " + json.dumps(starts) + ";\n")

# ---- captions composition ----
cap_items, cap_js = [], []
for l in lines:
    name, col = E.SPEAKERS[l["who"]]
    note = f' <em>({html.escape(l["note"])})</em>' if l["note"] else ""
    cap_items.append(
        f'    <div id="cap-{l["id"]}" class="clip cap" data-start="{l["at"]}" data-duration="{l["dur"]}">\n'
        f'      <div id="cap-{l["id"]}-box" class="cap-box"><span class="cap-who" style="color: {col}">{html.escape(name)}{note}</span>'
        f'<span class="cap-txt">{html.escape(l["text"])}</span></div>\n'
        f"    </div>"
    )
    cap_js.append(
        f'      tl.fromTo("#cap-{l["id"]}-box", {{ opacity: 0, y: 24, scale: 0.96 }}, '
        f'{{ opacity: 1, y: 0, scale: 1, duration: 0.18, ease: "power3.out" }}, {l["at"]});'
    )
captions = f"""<template>
  <style>
    #root {{
      position: absolute;
      inset: 0;
      pointer-events: none;
    }}
    .cap {{
      position: absolute;
      left: 0;
      right: 0;
      bottom: 64px;
      display: flex;
      justify-content: center;
    }}
    .cap-box {{
      max-width: 1500px;
      padding: 14px 34px 18px;
      border-radius: 22px;
      background: rgba(14, 16, 22, 0.82);
      border: 3px solid rgba(255, 255, 255, 0.12);
      text-align: center;
      font-family: "Baloo 2", sans-serif;
    }}
    .cap-who {{
      display: block;
      font-size: 28px;
      line-height: 32px;
      font-weight: 800;
      letter-spacing: 0.06em;
    }}
    .cap-who em {{
      font-style: normal;
      font-weight: 500;
      color: #c9ced6;
      letter-spacing: 0;
    }}
    .cap-txt {{
      display: block;
      color: #ffffff;
      font-size: 46px;
      line-height: 54px;
      font-weight: 700;
    }}
  </style>
  <div id="root" data-composition-id="captions" data-width="1920" data-height="1080">
{chr(10).join(cap_items)}
  </div>
  <script>
    (function () {{
      const tl = gsap.timeline({{ paused: true }});
{chr(10).join(cap_js)}
      window.__timelines["captions"] = tl;
    }})();
  </script>
</template>
"""
with open(os.path.join(ROOT, "compositions/captions.html"), "w") as f:
    f.write(captions)

# ---- scene compositions ----
for sid, dur, title in E.SCENES:
    src = os.path.join(HERE, "scenes", sid + ".js")
    if not os.path.exists(src):
        print(f"warning: no scene script {src}", file=sys.stderr)
        continue
    body = open(src).read().rstrip()
    body = "\n".join(("      " + ln) if ln.strip() else "" for ln in body.split("\n"))
    out = f"""<template>
  <style>
    #root {{
      position: absolute;
      inset: 0;
      overflow: hidden;
      background: #000;
    }}
    #{sid}-cv {{
      position: absolute;
      inset: 0;
      width: 1920px;
      height: 1080px;
    }}
  </style>
  <div id="root" data-composition-id="{sid}" data-width="1920" data-height="1080">
    <canvas
      id="{sid}-cv"
      class="clip"
      data-start="0"
      data-duration="{dur}"
      width="1920"
      height="1080"
      data-layout-allow-overflow
    ></canvas>
  </div>
  <script>
    /* {html.escape(title)} — generated by tools/build.py from tools/scenes/{sid}.js */
    (function () {{
      const START = {starts[sid]};
      const DUR = {dur};
{body}
    }})();
  </script>
</template>
"""
    with open(os.path.join(ROOT, "compositions", sid + ".html"), "w") as f:
        f.write(out)

# ---- index.html ----
hosts = []
for sid, dur, title in E.SCENES:
    hosts.append(
        f"""      <div
        id="{sid}"
        data-composition-id="{sid}"
        data-composition-src="compositions/{sid}.html"
        data-start="{starts[sid]}"
        data-duration="{dur}"
        data-track-index="1"
        data-track-kind="graphics"
        data-width="1920"
        data-height="1080"
        style="z-index: 1"
      ></div>"""
    )
audio = []
for i, (fname, a, b, vol) in enumerate(E.BEDS):
    st = starts[a]
    en = starts[b] + DUR[b]
    audio.append(
        f'      <audio id="bed-{i}" class="clip" src="assets/sfx/{fname}" data-start="{st}" '
        f'data-duration="{round(en - st, 2)}" data-track-index="3" data-volume="{vol}" '
        f'data-fade-in="0.8" data-fade-out="0.8"></audio>'
    )
sfx_durs = {
    "pop.mp3": 0.5,
    "click.mp3": 0.4,
    "notification.mp3": 1.0,
    "sparkle.mp3": 1.4,
    "chime.mp3": 1.4,
    "whoosh.mp3": 0.57,
    "whoosh-short.mp3": 0.57,
}
lane_end = []  # simple lane packing for overlapping effects
for i, (sid, lt, fname, vol, d) in enumerate(sorted(E.SFX, key=lambda x: starts[x[0]] + x[1])):
    st = round(starts[sid] + lt, 3)
    d = d or sfx_durs.get(fname, 1.0)
    lane = 0
    while lane < len(lane_end) and lane_end[lane] > st:
        lane += 1
    if lane == len(lane_end):
        lane_end.append(0)
    lane_end[lane] = st + d
    audio.append(
        f'      <audio id="sfx-{i}" class="clip" src="assets/sfx/{fname}" data-start="{st}" '
        f'data-duration="{d}" data-track-index="{4 + lane}" data-volume="{vol}"></audio>'
    )

index = f"""<!doctype html>
<html lang="az">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <title>Əmiraslan — 1-ci bölüm</title>
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <script src="assets/lib/core.js"></script>
    <script src="assets/lib/heads.js"></script>
    <script src="assets/lib/rig.js"></script>
    <script src="assets/lib/sets.js"></script>
    <script src="assets/lib/dialogue.js"></script>
    <style>
      @font-face {{
        font-family: "Bangers";
        src: url("assets/fonts/Bangers.ttf") format("truetype");
      }}
      @font-face {{
        font-family: "Baloo 2";
        src: url("assets/fonts/Baloo2.ttf") format("truetype");
        font-weight: 400 800;
      }}
      * {{
        margin: 0;
        padding: 0;
        box-sizing: border-box;
      }}
      html,
      body {{
        width: 1920px;
        height: 1080px;
        overflow: hidden;
        background: #000;
      }}
      #root {{
        position: relative;
        width: 100%;
        height: 100%;
      }}
      #stage-ground {{
        position: absolute;
        inset: 0;
        background: #000;
      }}
    </style>
  </head>
  <body>
    <div
      id="root"
      data-composition-id="main"
      data-start="0"
      data-duration="{TOTAL}"
      data-width="1920"
      data-height="1080"
    >
      <div id="stage-ground"></div>
{chr(10).join(hosts)}
      <div
        id="captions"
        data-composition-id="captions"
        data-composition-src="compositions/captions.html"
        data-start="0"
        data-duration="{TOTAL}"
        data-track-index="2"
        data-track-kind="captions"
        data-width="1920"
        data-height="1080"
        style="z-index: 5"
      ></div>
{chr(10).join(audio)}
    </div>
    <script>
      window.__timelines = window.__timelines || {{}};
      window.__timelines["main"] = gsap.timeline({{ paused: true }});
    </script>
  </body>
</html>
"""
with open(os.path.join(ROOT, "index.html"), "w") as f:
    f.write(index)
print(f"built: {len(E.SCENES)} scenes, {len(lines)} lines, {len(E.SFX)} sfx, total {TOTAL}s")
